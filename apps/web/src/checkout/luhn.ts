/** Luhn checksum over a string of digits. Length is the caller's concern. */
export function luhnValid(digits: string): boolean {
  if (!/^\d+$/u.test(digits)) return false;
  let sum = 0;
  let double = false;
  for (let i = digits.length - 1; i >= 0; i -= 1) {
    let d = Number(digits[i]);
    if (double) {
      d *= 2;
      if (d > 9) d -= 9;
    }
    sum += d;
    double = !double;
  }
  return sum % 10 === 0;
}
